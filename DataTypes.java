class DataTypes{
	public static void main(String[] args) {
		byte b=127;
		short s=32767;
		int i=200;
		long l=400;
		float f=2.5f;
		double d=0.00000235;
		char ch=';';
		boolean bo=true;
		System.out.println(b+"\n"+s+"\n"+i+"\n"+l+"\n"+f+"\n"+d+"\n"+ch+"\n"+bo);
		char ch1=67;
		System.out.println(ch1);
		String str1=new String("Hello");
		String str2="Hello";
		System.out.println(str1+" "+str2);
	}
}